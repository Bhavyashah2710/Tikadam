// Checks content coverage vs syllabus; rewrites CONTENT_PROGRESS.md. Statuses: PENDING/GENERATED/NEEDS_REVIEW (VALIDATED is set only after human/full-validator review).
import fs from "fs";
const sy="src/data/syllabus/",ct="src/data/content/";
const idx=JSON.parse(fs.readFileSync(sy+"subjects.json","utf8"));
const req=["definition","simpleExplanation","realLifeAnalogy","example","keyPoints","quickRevision","mustKnow","ifYouKnow","commonMistakes","examQuestions","knowledgeCheck"];
const min={keyPoints:4,mustKnow:2,ifYouKnow:3,commonMistakes:2,examQuestions:1,knowledgeCheck:5};
const prev=fs.existsSync("CONTENT_PROGRESS.md")?fs.readFileSync("CONTENT_PROGRESS.md","utf8"):"";
const keep=new Set([...prev.matchAll(/\| (\S+-t\d+) \| .*\| VALIDATED \|/g)].map(m=>m[1]));
const out=["# CONTENT_PROGRESS","","Status values: PENDING · GENERATED · VALIDATED · NEEDS_REVIEW","(auto-generated by `node scripts/content-status.mjs`)",""];
let tot=0,gen=0,rev=0;const lines=[];const issues=[];
for(const s of idx.subjects){
  const j=JSON.parse(fs.readFileSync(sy+s.file,"utf8"));
  const f=ct+s.id+".json";const c=fs.existsSync(f)?JSON.parse(fs.readFileSync(f,"utf8")):{};
  let sg=0,st=0;const sec=[];
  for(const ch of j.chapters){
    sec.push(`### Ch${ch.number} ${ch.title}`,"","| ID | Topic | Status |","|---|---|---|");
    for(const t of ch.topics){tot++;st++;
      const e=c[t.id];let status="PENDING";
      if(e){const miss=req.filter(k=>e[k]===undefined||e[k]===""||(Array.isArray(e[k])&&!e[k].length));
        const low=Object.entries(min).filter(([k,n])=>Array.isArray(e[k])&&e[k].length<n&&e[k].length>0).map(([k,n])=>`${k}<${n}`);
        if(miss.length||low.length){status="NEEDS_REVIEW";rev++;issues.push(`${t.id}: ${[...miss.map(m=>"missing "+m),...low].join(", ")}`);}
        else{status=keep.has(t.id)?"VALIDATED":"GENERATED";gen++;sg++;}}
      sec.push(`| ${t.id} | ${t.title} | ${status} |`);}
    sec.push("");}
  for(const id of Object.keys(c)) if(!j.chapters.some(ch=>ch.topics.some(t=>t.id===id))) issues.push(`ORPHAN content id ${id}`);
  lines.push(`## ${s.name} — ${sg}/${st} generated`,"",...sec);
}
out.push(`**Total ${tot} topics — GENERATED/VALIDATED ${gen} · NEEDS_REVIEW ${rev} · PENDING ${tot-gen-rev}**`,"",...lines);
fs.writeFileSync("CONTENT_PROGRESS.md",out.join("\n")+"\n");
console.log(`topics=${tot} complete=${gen} needs_review=${rev} pending=${tot-gen-rev}`);
issues.forEach(i=>console.log(" -",i));
